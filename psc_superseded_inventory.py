#!/usr/bin/env python3
"""Inventory/delete exact obsolete PSC 1.5.1/1.5.2 derived artifacts only.

Deletion requires a verified replacement receipt and a previously saved manifest.
Source data, JSON provenance, code and attributed review decisions are retained.
"""
import argparse,datetime,hashlib,json,os,re,zipfile
from pathlib import Path
VERSIONS={'1.5.1','1.5.2'}

def dataless(p):
 return bool(getattr(p.stat(),'st_flags',0) & 0x40000000)
PATTERN=re.compile(r'(?:psc[_ .-]*v?1[._]5[._][12]|v151r081|psc1\.5\.[12])',re.I)

def sha(p):
 h=hashlib.sha256()
 with Path(p).open('rb') as f:
  for b in iter(lambda:f.read(1048576),b''):h.update(b)
 return h.hexdigest()

def inventory(root,output):
 root=root.resolve(); candidates={};metadata=[];archives=[];protected=set();skipped=[]
 def add(p,reason,version):
  if not p.is_file() or p.is_symlink():return
  if p.suffix.lower() in {'.json','.toml','.npy','.pickle','.pkl','.py','.md','.txt'}:return
  if any(token in p.name.lower() for token in ['decision','annotation','worksheet']):return
  candidates[str(p.resolve())]=dict(path=str(p.resolve()),reason=reason,version=version,bytes=p.stat().st_size,mtime_ns=p.stat().st_mtime_ns,inode=p.stat().st_ino,dataless=dataless(p))
 for base,dirs,files in os.walk(root):
  dirs[:]=[d for d in dirs if d not in {'.git','code','finalization_code','input','inputs','__pycache__','idtracker_output','idtracker_sessions','preprocessing','trajectories'} and not d.startswith(('psc_1_6_0','psc_regenerated','psc_raw_priority','psc_withdrawal'))]
  folder=Path(base)
  for name in files:
   p=folder/name
   known_local_release=next((part for part in p.relative_to(root).parts if part in {'dyadic_pilot25_20260930','grouptrial_2024_9000_official_21','grouptrial_2024_9000_official_26','grouptrial_2024_remaining_5_9000_progress','grouptrial_additional_psc_v151r081_20260925'}),None)
   if known_local_release and p.suffix.lower() in {'.pdf','.csv','.npz','.html','.mp4'} and (any(x in p.parts for x in ['analysis','analysis_v151r081','review','review_compare_v3','outlined_pdf','pdf_outline_v1','individual_videos']) or p.name in {'START_HERE.html','RUN_INDEX.csv','ZIP_INDEX.csv'}):
    add(p,'Derived artifact in explicitly identified superseded local release '+known_local_release,'1.5.2' if known_local_release.startswith('dyadic_pilot25') else '1.5.1')
   if p.suffix.lower()=='.zip':archives.append(p)
   if dataless(p):
    if PATTERN.search(str(p)) and p.suffix.lower() in {'.pdf','.csv','.npz','.html','.mp4'} and any(x in p.parts for x in ['analysis','analysis_v151r081','review','review_compare_v3','outlined_pdf','pdf_outline_v1','individual_videos']):
     add(p,'Online-only derived artifact inside explicitly versioned obsolete release; no hydration required','1.5.x')
    if p.name in {'manifest.json','source_manifest.json','render_manifest.json'}:skipped.append(dict(path=str(p),reason='Online-only provenance retained without downloading'))
    continue
   if name not in {'manifest.json','source_manifest.json','render_manifest.json'}:continue
   try:m=json.loads(p.read_text())
   except (OSError,ValueError):continue
   version=m.get('persistent_model_version',m.get('psc_model_version'))
   if version not in VERSIONS:continue
   metadata.append(str(p))
   for key in ['trajectory_file','blob_evidence_file','video_source','source_toml']:
    if m.get(key):protected.add(str(Path(m[key]).resolve()))
   if m.get('decision_count',0) or 'HUMAN' in str(m.get('status','')) or m.get('qc_status','UNREVIEWED')!='UNREVIEWED':
    skipped.append(dict(path=str(p),reason='Attributed/human review requires preservation'));continue
   if name=='manifest.json' and m.get('persistent_model_version'):
    for q in folder.iterdir():
     if q.suffix.lower() in {'.csv','.pdf','.npz','.png','.svg','.html'}:add(q,'Analysis generated by old PSC model',version)
   elif name=='source_manifest.json':
    for key in ['html','video']:
     if m.get(key) and Path(m[key]).name==m[key]:add(folder/m[key],'Old PSC synchronized review derivative',version)
   elif name=='render_manifest.json' and m.get('pdf_filename'):
    add(folder/Path(m['pdf_filename']).name,'Old PSC derived outlined PDF',version)
 # Include generated aggregate reports/duplicate media in manifest-confirmed old release roots.
 release_roots={root/Path(p).relative_to(root).parts[0] for p in metadata}
 for release in release_roots:
  for base,dirs,files in os.walk(release):
   dirs[:]=[d for d in dirs if d not in {'code','input','inputs','idtracker_output','idtracker_sessions','preprocessing','trajectories','__pycache__','finalization_code'}]
   for name in files:
    p=Path(base)/name
    if p.suffix.lower() not in {'.mp4','.pdf','.html','.csv','.npz'}:continue
    # Inventory and run manifests are provenance, not obsolete measurements.
    if p.suffix.lower()=='.csv' and any(t in name.lower() for t in ['manifest','inventory','plan','source','excluded','exclusion','worksheet','decision','annotation']):continue
    add(p,'Generated media/table/index in manifest-confirmed obsolete release','1.5.x')
 # Version-tagged archives are packaged derived releases. Verify embedded model.
 for p in archives:
  if not PATTERN.search(str(p)):continue
  if dataless(p):
   add(p,'Online-only ZIP explicitly named for superseded PSC version','1.5.x');continue
  try:
   with zipfile.ZipFile(p) as z:
    members=z.namelist()
    if any('decision' in Path(n).name.lower() or 'annotation' in Path(n).name.lower() for n in members if not n.endswith(('.py','.js','.md'))):
     skipped.append(dict(path=str(p),reason='Potential attributed review data in archive'));continue
    versions=set()
    for n in members:
     if Path(n).name in {'manifest.json','source_manifest.json','render_manifest.json'}:
      info=z.getinfo(n)
      if info.file_size>2000000:continue
      m=json.loads(z.read(n));v=m.get('persistent_model_version',m.get('psc_model_version'))
      if v:versions.add(v)
    if versions and versions<=VERSIONS:add(p,'ZIP containing only superseded PSC models',','.join(sorted(versions)))
    else:skipped.append(dict(path=str(p),reason='Archive version not exclusively confirmed obsolete',versions=sorted(versions)))
  except (OSError,ValueError,zipfile.BadZipFile) as e:skipped.append(dict(path=str(p),reason=str(e)))
 # Remove proven source paths even if a malformed folder layout included one.
 for p in protected:candidates.pop(p,None)
 for r in candidates.values():r['sha256']=None if r['dataless'] else sha(r['path'])
 report=dict(created_utc=datetime.datetime.now(datetime.timezone.utc).isoformat(),root=str(root),
             obsolete_models=sorted(VERSIONS),candidates=list(candidates.values()),
             matched_manifests=metadata,protected_source_paths=sorted(protected),skipped=skipped,
             count=len(candidates),bytes=sum(r['bytes'] for r in candidates.values()))
 output.write_text(json.dumps(report,indent=2)+'\n')
 print(json.dumps({k:report[k] for k in ['root','count','bytes']},indent=2))

def delete(manifest,replacement,receipt):
 replacement_data=json.loads(replacement.read_text())
 if replacement_data.get('status')!='COMPLETE_UNREVIEWED' or replacement_data.get('psc_model_version')!='1.6.0' or replacement_data.get('run_count')!=51:
  raise ValueError('Replacement is not the verified complete 51-run PSC 1.6.0 release')
 if not all(replacement_data.get(k) for k in ['all_encoded_frame_counts_verified','all_pdf_versions_verified','all_raw_psc_csvs_verified','source_inputs_unchanged','zip_integrity_passed']):raise ValueError('Replacement checks incomplete')
 m=json.loads(manifest.read_text());root=Path(m['root']).resolve()
 protected={p:dict(sha256=None if dataless(Path(p)) else sha(p),bytes=Path(p).stat().st_size,mtime_ns=Path(p).stat().st_mtime_ns) for p in m['protected_source_paths'] if Path(p).is_file()}
 for r in m['candidates']:
  p=Path(r['path'])
  st=p.stat()
  same=(st.st_size==r['bytes'] and st.st_mtime_ns==r['mtime_ns'] and st.st_ino==r['inode'])
  if not p.is_relative_to(root) or p.is_symlink() or not same or (r['sha256'] and sha(p)!=r['sha256']):raise ValueError('Candidate changed or escaped scope: '+str(p))
 removed=[]
 for r in m['candidates']:
  Path(r['path']).unlink();removed.append(r['path'])
 for p,record in protected.items():
  if Path(p).stat().st_size!=record['bytes'] or Path(p).stat().st_mtime_ns!=record['mtime_ns'] or (record['sha256'] and sha(p)!=record['sha256']):raise ValueError('Source changed: '+p)
 if any(Path(p).exists() for p in removed):raise ValueError('Deletion not complete')
 receipt.write_text(json.dumps(dict(status='DELETED_VERIFIED',count=len(removed),bytes=m['bytes'],
  inventory_sha256=sha(manifest),replacement_receipt_sha256=sha(replacement),
  protected_source_checks=protected,removed=removed),indent=2)+'\n')
 print(json.dumps(dict(status='DELETED_VERIFIED',count=len(removed),bytes=m['bytes'])))

if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('action',choices=['inventory','delete']);p.add_argument('--root',type=Path);p.add_argument('--manifest',type=Path,required=True);p.add_argument('--replacement',type=Path);p.add_argument('--receipt',type=Path);a=p.parse_args()
 if a.action=='inventory':inventory(a.root,a.manifest)
 else:delete(a.manifest,a.replacement,a.receipt)
